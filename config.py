class DiffConfig:
    """差分比較関連の設定"""

    # ── 差分抽出オプション（旧: Step 4「オプション設定」。2026-09 にUIから移行）──

    # 移動しただけのラベルを差分から除外する
    #   回路ブロックをまるごと別の位置に移動すると、座標単位の比較では
    #   「削除＋追加」として検出されます。同一ラベルの削除件数と追加件数が
    #   一致する分は、座標が異なっていても diff_labels.xlsx の変更候補から
    #   除外し、変更なしとして扱います（差分DXFのエンティティ比較には
    #   影響しません）。「☆」を含むラベルは対象外（常に変更候補として残ります）。
    #
    #   注意: 座標を見ず件数だけで判定するため、たまたま同じラベル名の部品が
    #   別の場所で削除・別の無関係な場所に追加された場合も「移動」とみなされ、
    #   見た目上区別できなくなります。
    IGNORE_MOVED_LABELS = False

    # 色だけが異なる図形は変更なし扱いにする
    #   座標・形状（線の始点終点、円の中心・半径、文字内容等）が完全に一致し、
    #   色（color）だけが異なる図形要素を、差分DXFで UNCHANGED（変更なし）として
    #   扱います。改訂箇所を色分けマーキングした図面などで、同じ図形が色の違いだけで
    #   DELETED＋ADDED の組として大量に検出される場合に使用します
    #   （diff_labels.xlsx のラベル比較には影響しません）。
    #
    #   注意: 色の変更自体が意図的な改訂マーキングである場合、この機能を
    #   有効にするとその色変更が差分として検出されなくなります。
    IGNORE_COLOR_ONLY_CHANGES = False

    # 差分検出の際の座標マージン
    #   同じ図形と判定する座標の許容誤差です。大きくするほど位置ずれを無視します。
    DEFAULT_TOLERANCE = 0.05

    # レイヤー色設定（AutoCADカラーインデックス）
    #   1=赤 / 2=黄 / 3=緑 / 4=シアン / 5=青 / 6=マゼンタ / 7=白・黒 / 8=灰 / 9=明灰
    #
    #   2026-09-18、オフセット補正機能の組み込みに伴い、差分DXFを7レイヤー構成に
    #   変更（DXF-visual-diffから移植）。外部CADソフトでの閲覧を前提に、
    #   「OLD_ALLを1枚ONにすれば流用元ファイルの全図形が色の区別つきで再現できる」
    #   「NEW_ALLを1枚ONにすれば流用先ファイルの全図形が色の区別つきで再現できる」
    #   ようにした。DXFの色はレイヤー属性ではなくエンティティ属性として
    #   各図形に直接書き込まれるため、1レイヤーに複数カテゴリが混在しても
    #   色による区別は失われない。
    DEFAULT_DELETED_COLOR = 6             # OLD_DELETED（削除図形。流用元図面のみに存在）
    DEFAULT_ADDED_COLOR = 4               # NEW_ADDED（追加図形。流用先図面のみに存在）
    DEFAULT_UNCHANGED_COLOR = 7           # UNCHANGED（変更なし図形。OLD/NEW共通1レイヤー）
    DEFAULT_UNCHANGED_OFFSET_OLD_COLOR = 8  # OLD_UNCHANGED_OFFSET（オフセット一致・OLD側旧位置。濃灰）
    DEFAULT_UNCHANGED_OFFSET_NEW_COLOR = 9  # NEW_UNCHANGED_OFFSET（オフセット一致・NEW側新位置。明灰）

    # ── オフセット補正の自動検出（2026-09-18、DXF-visual-diffから移植）──
    #   ファイルOLD・NEWで一致しなかった図形どうしを、位置に依存しない「形状」で
    #   対応付け、そのアンカー座標の差分（＝移動量）をオフセット候補として
    #   クラスタリングする。候補ごとに実際どれだけの図形が一致するかを検証し、
    #   下記のしきい値を満たしたものだけを UNCHANGED_OFFSET として採用する。
    #   複数のオフセットが同時に検出されうる（回路ブロックが複数箇所で
    #   別々に移動している場合など）。
    #
    #   DXF-visual-diffと異なり、本プロジェクトではオプション自体の有効/無効を
    #   Step4画面のチェックボックス「オフセット補正を行う」（既定ON）で
    #   ユーザーが選択できる。下記のしきい値は挙動を揃えるためDXF-visual-diffの
    #   実測値をそのまま踏襲している——各値の調整理由・実測根拠は
    #   DXF-visual-diff の config.py のコメント（同名定数）を参照。

    # 採用に必要な最小一致件数
    AUTO_OFFSET_MIN_MATCHES = 10

    # 採用に必要な最小形状種類数（偽陽性ガード）
    AUTO_OFFSET_MIN_DISTINCT_SHAPES = 5

    # 採用するオフセットの最大個数（出力の複雑さに対する安全上限）
    AUTO_OFFSET_MAX_OFFSETS = 50

    # 検証する候補オフセットの上限（得票数の多い順に上位N個のみ検証する）
    AUTO_OFFSET_MAX_CANDIDATES = 200

    # 候補生成時、同一形状の出現数がこれを超える場合は対応付けが曖昧なため
    # 候補生成から除外する（組み合わせ爆発の防止も兼ねる）
    AUTO_OFFSET_MAX_INSTANCES_PER_SHAPE = 8

    # ── コンパクト救済 ──
    #   AUTO_OFFSET_MIN_MATCHES/MIN_DISTINCT_SHAPES の条件を満たさない場合でも、
    #   一致した図形が狭い範囲にまとまっていれば「記号1個が移動した」とみなして
    #   採用する、第2の採用経路です（どちらかの条件を満たせば採用）。

    # コンパクト救済の最小一致件数（AUTO_OFFSET_MIN_MATCHESより緩い値にする）
    AUTO_OFFSET_COMPACT_MIN_MATCHES = 4

    # コンパクト救済の最小形状種類数（AUTO_OFFSET_MIN_DISTINCT_SHAPESより緩い値にする）
    AUTO_OFFSET_COMPACT_MIN_DISTINCT_SHAPES = 2

    # コンパクト救済で許容する広がり（一致した図形のアンカー座標のバウンディング
    # ボックス対角長）の上限。これを超える場合は「散在した偶然の一致」とみなし
    # 不採用にする。
    AUTO_OFFSET_COMPACT_MAX_SPAN = 15.0

    # ZIPファイル名
    OUTPUT_ZIP_FILENAME = "dxf_diff_results.zip"
    MASTER_FILENAME = "Parent-Child_list.xlsx"


class LabelFilterConfig:
    """差分抽出するラベルの絞り込み設定"""

    # 差分抽出するラベルの先頭文字列（正規表現・複数指定可）
    #   ここに書いた正規表現のいずれかに「先頭から」一致するラベルだけを
    #   diff_labels.xlsx の差分（変更候補）として出力します。
    #   旧ラベル・新ラベルのどちらかが一致すればその行は残ります。
    #
    #   空リスト（既定）の場合はフィルタをかけず、すべてのラベルが
    #   差分抽出の対象になります。
    #
    #   差分DXF（図形の ADDED/DELETED/UNCHANGED 判定）には影響しません。
    #
    #   記述例:
    #     DIFF_LABEL_PREFIX_PATTERNS = [
    #         r"W No\.",          # 「W No.」で始まるラベル
    #         r"[A-Z]{1,3}\d+",   # 機器符号らしいラベル（R10, CB001 など）
    #     ]
    DIFF_LABEL_PREFIX_PATTERNS = []


class ExtractionConfig:
    """DXF抽出関連の設定"""

    # 図番抽出設定
    # 両フォーマット対応: XX0000-000-00X（長）、XX0000-000X（短）
    DRAWING_NUMBER_PATTERN = r'[A-Z]{2}\d{4}-\d{3}(?:-\d{2})?[A-Z]'  # 図番パターン

    # 距離設定（DXF単位）
    SOURCE_LABEL_PROXIMITY = 80     # 流用元図番ラベルからの検出距離
    DWG_NO_LABEL_PROXIMITY = 80     # DWG No.ラベルからの検出距離
    TITLE_PROXIMITY_X = 80          # TITLEラベルからの横方向検出距離

    # RevUpペア設定
    RIGHTMOST_DRAWING_TOLERANCE = 100.0  # 右端図面判定の許容範囲


